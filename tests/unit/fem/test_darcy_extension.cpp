   MarkLevelSetSubdomain(bg, BallPhi, offset, m1, cp, gamma);

   const real_t fit0 = BallFluxError(n, m0, nullptr);
   const real_t plain = BallFluxError(n, m0, &cp);
   TiltedPath tp(cp, BallPhi, 0.3, 0.5);
