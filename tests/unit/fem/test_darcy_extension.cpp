/// The closest-point foot on the disc, pushed along Gamma by a wave that
/// vanishes at both ends of every face: the images still cover Gamma exactly,
/// face by face, but along each face the foot runs forward, back and forward
/// again. A family that backtracks by construction, for the signed weight.
class WobblePath : public TransferPath
{
   const real_t amp;
public:
   explicit WobblePath(real_t amp_) : amp(amp_) { }
   void Endpoint(const Vector &, const Vector &, Vector &) const override
   { MFEM_ABORT("WobblePath is defined face by face"); }
   void Endpoint(FaceElementTransformations &FTr, const IntegrationPoint &ip,
                 Vector &xbar) const override
   {
      Vector x(2), c;
      FTr.SetAllIntPoints(&ip);
      FTr.Transform(ip, x);
      DiscCentre(c);
      const real_t th = std::atan2(x(1) - c(1), x(0) - c(0))
                        + amp * std::sin(2. * M_PI * ip.x);
      xbar.SetSize(2);
      xbar(0) = c(0) + disc_R * std::cos(th);
      xbar(1) = c(1) + disc_R * std::sin(th);
   }
};

/// The disc's closest-point family with no closed-form Jacobian, so the
/// quadratures difference it, recording how far outside its face's reference
/// interval [0, 1] it was ever asked to go.
class OffFacePath : public TransferPath
{
   const ClosestPointPath inner;
public:
   mutable real_t worst_outside = 0.;
   OffFacePath() : inner(SphereOnDisc()) { }
   static VectorPositionFunction SphereOnDisc()
   {
      Vector c; DiscCentre(c);
      return ClosestPointPath::Sphere(c, disc_R);
   }
   void Endpoint(const Vector &x, const Vector &n, Vector &xbar) const override
   { inner.Endpoint(x, n, xbar); }
   void Endpoint(FaceElementTransformations &FTr, const IntegrationPoint &ip,
                 Vector &xbar) const override
   {
      worst_outside = std::max(worst_outside, std::max(-ip.x, ip.x - 1.));
      inner.Endpoint(FTr, ip, xbar);
   }
};

/// Sum the boundary quadrature over Gamma_h. @a absolute sums |weight| instead,
/// which is the length the foot map TRAVERSES rather than the measure of
/// Gamma -- a different and larger quantity wherever the map backtracks.
real_t BoundarySum(Mesh &D_h, int gamma_h_attr, const TransferPath &path,
                   bool absolute = false, int ir_order = 20,
                   real_t fd_step = ExtensionFDStep())
{
   const IntegrationRule &ir = IntRules.Get(Geometry::SEGMENT, ir_order);
   real_t sum = 0.;
   for (int be = 0; be < D_h.GetNBE(); be++)
   {
      if (D_h.GetBdrAttribute(be) != gamma_h_attr) { continue; }
      FaceElementTransformations *FTr = D_h.GetBdrFaceTransformations(be);
      if (!FTr) { continue; }
      ExtensionBoundaryQuadrature(*FTr, path, ir,
                                  [&](const ExtensionBoundaryPoint &pt)
      { sum += absolute ? std::abs(pt.weight) : pt.weight; }, fd_step);
   }
   return sum;
}

/// The worst departure of the reported normal from the disc's own.
real_t WorstNormal(Mesh &D_h, int gamma_h_attr, const TransferPath &path,
                   int ir_order = 20)
{
   const IntegrationRule &ir = IntRules.Get(Geometry::SEGMENT, ir_order);
   Vector c; DiscCentre(c);
   real_t worst = 0.;
   for (int be = 0; be < D_h.GetNBE(); be++)
   {
      if (D_h.GetBdrAttribute(be) != gamma_h_attr) { continue; }
      FaceElementTransformations *FTr = D_h.GetBdrFaceTransformations(be);
      if (!FTr) { continue; }
      ExtensionBoundaryQuadrature(*FTr, path, ir,
                                  [&](const ExtensionBoundaryPoint &pt)
      {
         // On a circle the outward normal at y is (y - c)/R exactly.
         const real_t ex0 = (pt.y(0) - c(0)) / disc_R;
         const real_t ex1 = (pt.y(1) - c(1)) / disc_R;
         const real_t d = std::sqrt((pt.nu(0)-ex0)*(pt.nu(0)-ex0)
                                    + (pt.nu(1)-ex1)*(pt.nu(1)-ex1));
         worst = std::max(worst, d);
      });
   }
   return worst;
}

